namespace AppCanzoniere.Application.Interfaces;

/// <summary>
/// Service for AI-powered chord suggestions
/// </summary>
public interface IChordSuggestionService
{
    /// <summary>
    /// Get chord suggestions for a song based on title and artist
    /// </summary>
    Task<ChordSuggestionResult> GetChordSuggestionsAsync(string title, string artist, CancellationToken cancellationToken = default);

    /// <summary>
    /// Get chord suggestions with additional context (lyrics, key)
    /// </summary>
    Task<ChordSuggestionResult> GetChordSuggestionsWithContextAsync(
        string title, 
        string artist, 
        string? lyrics = null, 
        string? key = null,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Check if the service is available and configured
    /// </summary>
    Task<bool> IsAvailableAsync(CancellationToken cancellationToken = default);
}

/// <summary>
/// Result from chord suggestion service
/// </summary>
public class ChordSuggestionResult
{
    public bool Success { get; set; }
    public string? ChordProContent { get; set; }
    public string? OriginalKey { get; set; }
    public string? ErrorMessage { get; set; }
    public string? Source { get; set; } // e.g., "Perplexity AI", "OpenAI"
    public DateTime RequestedAt { get; set; } = DateTime.UtcNow;
    
    /// <summary>
    /// Disclaimer text for copyright
    /// </summary>
    public string DisclaimerText { get; set; } = 
        "This content was generated by AI and may be subject to copyright. " +
        "Please verify accuracy and ensure you have proper rights before using.";
}
